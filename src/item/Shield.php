declare(strict_types=1);

namespace pocketmine\item;

/**
 * A shield: held in either hand, it blocks attacks coming from the front while the holder sneaks (Bedrock behaviour).
 * The blocking itself is resolved in {@link \pocketmine\player\Player::attack()}.
 */
class Shield extends Durable{

	public function getMaxDurability() : int{
		return 336;
	}

	public function getMaxStackSize() : int{
		return 1;
	}
}
